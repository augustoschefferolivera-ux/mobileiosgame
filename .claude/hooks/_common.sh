#!/bin/bash
# Funções compartilhadas pelos hooks. Carregue com: . "$(dirname "$0")/_common.sh"
# Resolve a raiz do projeto (mesma precedência do Claude-Code-Game-Studios, MIT):
#   1. cwd contém .claude/            -> cwd
#   2. CLAUDE_PROJECT_DIR definido    -> ele
#   3. localização deste script       -> <raiz>/.claude/hooks/../..
resolve_root() {
  if [ -d ".claude" ]; then
    printf '%s' "$PWD"
  elif [ -n "${CLAUDE_PROJECT_DIR:-}" ] && [ -d "${CLAUDE_PROJECT_DIR}" ]; then
    printf '%s' "$CLAUDE_PROJECT_DIR"
  else
    (cd "$(dirname "${BASH_SOURCE[0]}")/../.." 2>/dev/null && pwd)
  fi
}

# Lê um campo simples de um JSON vindo do stdin, usando python3 quando existe.
# Uso: json_field '<json>' 'tool_input.command'
json_field() {
  local json="$1" path="$2"
  if command -v python3 >/dev/null 2>&1; then
    printf '%s' "$json" | python3 -I -c '
import json,sys
path=sys.argv[1].split(".")
try:
    d=json.load(sys.stdin)
except Exception:
    sys.exit(0)
for p in path:
    if isinstance(d,dict) and p in d: d=d[p]
    else: sys.exit(0)
if isinstance(d,(dict,list)): print(json.dumps(d))
else: print(d if d is not None else "")
' "$path" 2>/dev/null
  fi
}

