# Arquivos que o scanner ignora (documentação, notas, próprio framework).
is_scannable_path() {
  case "$1" in
    *.md|*.txt|*.json|*.yaml|*.yml) return 1 ;;
    */.claude/*|*/playbook/*|*/research_notes/*|*/reports/*|*/templates/*|*/node_modules/*|*/.git/*) return 1 ;;
    *) return 0 ;;
  esac
}
