/** Componentes x e y das 256 direções, em double. */
export const DIRECAO_X = new Float64Array(DIRECOES);
export const DIRECAO_Y = new Float64Array(DIRECOES);

for (let k = 0; k < POR_QUADRANTE; k++) {
  const x = QUADRANTE[2 * k]!;
  const y = QUADRANTE[2 * k + 1]!;
  for (let q = 0; q < 4; q++) {
    // Rotação de q × 90°: (x, y) → (−y, x), exata em ponto flutuante (só troca e sinal).
    const [rx, ry] = q === 0 ? [x, y] : q === 1 ? [-y, x] : q === 2 ? [-x, -y] : [y, -x];
    DIRECAO_X[k + q * POR_QUADRANTE] = rx;
    DIRECAO_Y[k + q * POR_QUADRANTE] = ry;
  }
}
